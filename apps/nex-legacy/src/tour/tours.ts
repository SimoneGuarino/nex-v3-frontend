// Helper per ottenere gli step da una o più chiavi
export function getStepsFor(keys: TourKey[] | TourKey, role: Role) {
    const list = Array.isArray(keys) ? keys : [keys];
    const steps = list.flatMap((k) => TOUR_STEPS[k] ?? []);
    return steps
        .filter((s) => !s.roles || s.roles.includes(role))
        .filter((s) => (s.when ? s.when({ role }) : true))
        .map((s): Step => {
            const override = s.perRoleText?.[role];
            if (!override) {
                // niente override per questo ruolo → uso lo step originale
                return s;
            }

            // applico solo title/description/hint del ruolo, il resto resta uguale
            return {
                ...s,
                ...override,
            };
        });
}
